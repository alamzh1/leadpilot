export type PixelIconName = keyof typeof GLYPHS;
export const PIXEL_ICON_NAMES = Object.keys(GLYPHS) as PixelIconName[];

type Props = {
  name: PixelIconName;
  size?: 16 | 24 | 32;
  className?: string;
  /** Цвет клеток «+»; по умолчанию — голубой из палитры. */
  accent?: string;
};

export function PixelIcon({ name, size = 16, className, accent = "var(--color-cyan)" }: Props) {
  const rows = GLYPHS[name];
  const main: string[] = [];
  const extra: string[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === "#") main.push(`M${x} ${y}h1v1h-1z`);
      else if (ch === "+") extra.push(`M${x} ${y}h1v1h-1z`);
    }
  });
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {main.length > 0 && <path d={main.join("")} fill="currentColor" />}
      {extra.length > 0 && <path d={extra.join("")} fill={accent} />}
    </svg>
  );
}
