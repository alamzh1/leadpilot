/** Поиск демо-компании по названию: без учёта регистра, пробелов по краям и повторных пробелов. */
export function findDemoCompany(query: string): DemoCompany | undefined {
  const key = normalizeName(query);
  if (!key) return undefined;
  return DEMO_COMPANIES.find((c) => normalizeName(c.name) === key);
}

function normalizeName(value: string): string {
  return value.trim().replace(/\s+/g, " ").toLocaleLowerCase("ru-RU");
}
